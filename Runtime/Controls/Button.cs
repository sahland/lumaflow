            ButtonStyle buttonStyle,
            bool enabled = true,
            FocusNode? focusNode = null)
            : this(text, onPressed, ButtonVariant.Primary, buttonStyle, enabled, focusNode) {
        }

        internal Button(
            string text,
            Action onPressed,
            ButtonVariant variant,
            ButtonStyle? style,
            bool enabled,
            FocusNode? focusNode,
            bool replaceFocusNodeAttachment)
            : this(text, onPressed, variant, style, enabled, focusNode) {
            ReplaceFocusNodeAttachment = replaceFocusNodeAttachment;
        }

        /// <summary>
        /// Gets the button label.
        /// </summary>
        public string Text { get; }

        /// <summary>Gets the declarative content hosted by this button.</summary>
        public Widget Child { get; }

        /// <summary>Gets the optional accessibility label for child-based buttons.</summary>
        public string? SemanticsLabel { get; }

        /// <summary>
        /// Gets the semantic button style.
        /// </summary>
        public ButtonStyle? Style { get; }

        /// <summary>
        /// Gets the semantic style selected when <see cref="Style"/> is not supplied.
        /// </summary>
        public ButtonVariant Variant { get; }

        /// <summary>
        /// Gets whether the button accepts input.
        /// </summary>
        public bool Enabled { get; }

        /// <summary>
        /// Optional externally owned controller for requesting and observing focus.
        /// </summary>
        public FocusNode? FocusNode { get; }

        // Reactive semantic controls may replace their native Button during a state
        // transition. This preserves one external controller across that handoff.
        internal bool ReplaceFocusNodeAttachment { get; }

        internal bool HasCustomChild { get; }

        internal Action OnPressed { get; }

        internal override WidgetNode CreateNode() {
            return new ButtonNode(this);
        }
    }

