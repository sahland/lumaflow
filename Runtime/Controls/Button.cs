    internal sealed class IconNode : WidgetNode {
        public IconNode(Icon widget) : base(widget) { }
        protected override VisualElement CreateElement(BuildContext context) {
            var widget = (Icon)Widget;
            var image = new UnityEngine.UIElements.Image { focusable = false, scaleMode = ScaleMode.ScaleToFit };
            ApplyIcon(image, widget);
            image.style.flexShrink = 0f;
            return image;
        }

        internal override bool TryUpdate(Widget nextWidget) {
            if (!CanUpdateWith(nextWidget) || nextWidget is not Icon icon) return false;
            ReevaluateInheritedDependencies(() =>
            {
                ApplyIcon((UnityEngine.UIElements.Image)Element, icon);
                return true;
            });
            UpdateWidget(icon);
            return true;
        }
        protected override void OnInheritedChanged(InheritedAspect aspect) => ApplyIcon((UnityEngine.UIElements.Image)Element, (Icon)Widget);
        private void ApplyIcon(UnityEngine.UIElements.Image image, Icon widget) {
            var theme = Context.Theme?.IconTheme ?? ThemeData.FallbackIconTheme;
            image.name = $"lumaflow-icon-{widget.Data.Name}";
            image.vectorImage = Resources.Load<VectorImage>(widget.Data.ResourceId);
            image.tintColor = widget.Color ?? theme.Color;
            image.style.width = widget.Size ?? theme.Size;
            image.style.height = widget.Size ?? theme.Size;
        }
    }

